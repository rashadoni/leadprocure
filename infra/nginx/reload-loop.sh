#!/bin/sh
# Перезагрузка конфига раз в шесть часов — чтобы подхватить продлённый сертификат.
#
# Сертификат выписывает и продлевает не этот контейнер, а ACME-клиент на хосте, и
# nginx читает файл сертификата ОДИН раз при старте. Без перезагрузки вход начал бы
# отдавать просроченный сертификат через неделю, причём молча: страница открывается,
# а браузер ругается. Сертификат живёт неделю, шесть часов — с запасом.
#
# Лежит в /docker-entrypoint.d/, а не в command, по невидимой на первый взгляд
# причине: штатный entrypoint образа выполняет свои шаги (в том числе envsubst по
# шаблонам в /etc/nginx/templates) ТОЛЬКО если команда начинается с «nginx». Стоило
# подменить command на `sh -c`, и конфиг не отрисовывался вовсе — контейнер
# поднимался «здоровым» и не слушал ничего. Проверено: так и было.
#
# Файл обязан быть исполняемым: entrypoint пропускает неисполняемые со словами
# «ignoring, not executable» — то есть снова молча.
while :; do
  sleep 6h
  nginx -s reload 2>&1 || echo "[reload-loop] перезагрузка не удалась"
done &
