// `awards.winning_bid_id` получает `ON DELETE CASCADE`.
//
// В `init` связь объявлена `winning_bid_id uuid NOT NULL REFERENCES bids(id)` — без
// `ON DELETE`, то есть `NO ACTION`. Это единственное место, где строка ПОКУПАТЕЛЯ ссылается
// на строку ПОСТАВЩИКА, а каскады у них разные: `bids` уходит от `organizations` поставщика,
// `awards` — от `sourcing_events`, то есть от покупателя. Удаление организации обходит эти
// ветви отдельными подоператорами, и `NO ACTION` проверяется в конце СВОЕГО подоператора —
// значит, если ветвь поставщика исполнится первой, проверка увидит присуждение, которое ещё
// не удалено, и заблокирует удаление целиком.
//
// Замерено на живой схеме (изолированная база, 9 ноября 2026), оба случая:
//
//   удалить только поставщика           → ERROR: update or delete on table "bids" violates
//                                         foreign key constraint "awards_winning_bid_id_fkey"
//   удалить покупателя и поставщика
//   ОДНИМ оператором                    → проходит
//
// Условие — не о конечном состоянии, а о ГРАНИЦЕ ОПЕРАТОРА, и это важно, потому что именно
// формулировку «поставщика удаляют, покупатель остаётся» читатель будет пытаться обойти.
// Падает и тот случай, где к концу транзакции удалены ОБА — если двумя операторами и
// поставщик первым. Измерено на снимке прода, восемь форм удаления:
//
//   только поставщик-победитель              → падает
//   двумя операторами, сначала поставщик      → падает
//   только покупатель                        → проходит
//   все организации ОДНИМ оператором          → проходит (и устойчиво: восемь комплектов,
//                                              пять прогонов подряд)
//   двумя операторами, сначала покупатель     → проходит
//
// **Почему «одним оператором проходит» НЕ значит «безопасно».** Поймано падением чистки в
// `rfi-rfp.e2e-spec.ts`, а она удаляет обе организации одним оператором — формой, которая в
// измерениях проходит устойчиво. Объяснение нашлось в самом репозитории: чистка
// `multilot.e2e-spec.ts` несёт обход с описанием механизма — «A single multi-org DELETE can
// cascade supplier bids first and hit awards.winning_bid_id's RESTRICT FK», — и
// `award-standstill.e2e-spec.ts` обходит так же, удаляя организацию покупателя ПЕРЕД общим
// удалением по шаблону. То есть одиночный оператор может каскадить ветвь поставщика первой;
// он не безопасен, а лишь обычно проходит, и ни пять прогонов подряд, ни восемь комплектов
// редкую ветку плана не поймали. У `rfi-rfp` обхода нет — отсюда и падение.
//
// После этой миграции оба обхода становятся ненужными; снимать их стоит отдельной задачей,
// потому что это изменение тестов и смотреть на него надо своим разбором.
//
// **Кого это касается на самом деле.** Прод организации не удаляет — это делает только
// чистка e2e. То есть пользователям дефект не виден, а гейт он роняет случайно, и такое
// падение объясняют словами «перезапусти прогон». Правило этого репозитория («org FK —
// `ON DELETE CASCADE`») написано ровно против таких мин.
//
// CASCADE, а не SET NULL: колонка `NOT NULL`, и присуждение без победившей ставки
// бессмысленно — если ставки нет, нет и решения, которое на неё ссылалось.
//
