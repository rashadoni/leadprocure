// День выставления счёта принадлежит тому, кто счёт выставил, и позже не пересчитывается.
//
// `issued_at` — это `timestamptz`, то есть МОМЕНТ. День из момента получается только с
// поясом, а выгрузки брали его через `toISOString()`, то есть в UTC. В UTC — всегда, по
// построению такой строки, а не потому что контейнер в UTC: от `TZ` процесса она не
// двигается вообще. Поэтому это не тот дефект, который закрыла правка драйвера
// (`common/db/pg-date-type.ts`: там колонки ТИПА `date` приходили объектом `Date` на
// местной полуночи), а его сосед — момент верный, а день из него вынимали не в том поясе.
//
// В Баку (+04) счёт, выписанный между 00:00 и 04:00 местного времени, уносил в `IssueDate`
// УБЛ-документа и в колонку «Дата» реестра для 1С ПРЕДЫДУЩИЙ день. Экран при этом показывал
// правильный: веб печатает `issued_at` по поясу браузера. То есть продукт сам себе
// противоречил, и наружу — в e-qaimə — уходила та из двух дат, которая неверна.
//
// **Решение владельца (8 ноября 2026): день по Баку, зафиксировать.** Отдельная колонка
// `issue_date`, записываемая в момент выставления. Пояс берётся из `APP_TIMEZONE`
// (по умолчанию `Asia/Baku`) ОДИН раз — при записи, — и документ, ушедший в налоговую,
// свою дату больше не меняет: смена настройки у следующей установки не переписывает
// задним числом даты уже выданных счетов. Разбор вариантов — в
// `docs/invoice-issue-date-decision.md`.
//
// Приём в этом репозитории уже принят и описан в `AGENTS.md`: так же денормализованы
// `procurement_requests.approved_at` (бюджет режет по дате утверждения, а не создания) и
// `invoices.department_id` (чтобы оплата выжила при перенастройке заказа). Вопрос «а по
// какому поясу считать» из чтения уходит совсем: при чтении считать больше нечего.
//
// **У колонки НЕТ значения по умолчанию, и это сделано нарочно.** `DEFAULT CURRENT_DATE`
// дал бы день по поясу сессии Postgres (здесь `Etc/UTC`) — ровно тот дефект, от которого
// колонка и появилась, только теперь записанный в базу и незаметный. Без умолчания любой
// будущий INSERT, забывший про день, падает громко. Единственный путь записи —
// `InvoicesService.submit`.
//
// **Бэкфилл исторических строк — это применение того же правила назад, и это надо назвать
// прямо.** `(issued_at AT TIME ZONE 'Asia/Baku')::date` читает старые счета как бакинские
// дни. Для азербайджанского продукта это не догадка, а то же решение; но пояс здесь
// ЗАШИТ, а не взят из `APP_TIMEZONE`: миграция не читает конфигурацию приложения, и день
// уже выданного документа не должен зависеть от того, с какой переменной окружения её
// однажды запустили. Установке в другом поясе, у которой уже есть счета, эти строки
// придётся поправить самой — другого честного варианта нет: момент в базе есть, а пояс, в
// котором их выписывали, не хранился никогда.
