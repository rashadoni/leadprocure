import { useEffect, useState } from 'react';

// Время, по которому страница решает, истёк ли срок.
//
// `Date.now()` прямо в отрисовке читается один раз и больше не меняется: срок истекает сам,
// без действий человека, а страница об этом не узнаёт. На карточке закупки это выглядело как
// кнопка «Сделать контракт», которая остаётся серой до перезагрузки, хотя пауза уже кончилась.
//
// Поэтому вместо опроса раз в секунду — одна перерисовка в момент истечения БЛИЖАЙШЕГО из
// переданных сроков. Нет сроков впереди — нет и таймера.
//
// Хук зовут ДО любого раннего `return` компонента (правило React: одинаковое число хуков на
// каждой отрисовке), поэтому список сроков читают через `?.` — он бывает пустым.
export function useDeadlineTick(deadlines: Array<string | null | undefined>): number {
  const [nowMs, setNowMs] = useState(() => Date.now());
  const next = deadlines
    .map((d) => (d ? new Date(d).getTime() : NaN))
    .filter((t) => Number.isFinite(t) && t > nowMs)
    .sort((a, b) => a - b)[0];
  useEffect(() => {
    if (next === undefined) return;
    // Задержка ограничена сутками: `setTimeout` держит её в 32 битах, и всё, что дальше
    // ~24.8 суток, срабатывает НЕМЕДЛЕННО (пауза в 596 часов такое даёт). После срабатывания
    // хук перевзводится — зависимость `nowMs` изменилась, — так что далёкий срок обходится
    // сутками, а не одним ложным «истёк».
    //
    // Цикла из этого не выходит: как только `nowMs` перешагнул срок, тот выпадает из `next`
    // (фильтр `t > nowMs`), `next` становится undefined и эффект выходит сразу.
    const DAY = 24 * 60 * 60 * 1000;
    // +1000 мс, чтобы перерисовка случилась уже ПОСЛЕ срока, а не на его границе.
    const delay = Math.min(Math.max(next - Date.now() + 1000, 0), DAY);
    const id = setTimeout(() => setNowMs(Date.now()), delay);
    return () => clearTimeout(id);
  }, [next, nowMs]);
  return nowMs;
}
